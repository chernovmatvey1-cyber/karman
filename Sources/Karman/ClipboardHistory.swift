import AppKit

/// Последние копирования (⌘C). Буфер обмена не присылает уведомлений,
/// поэтому раз в полсекунды сверяем его счётчик изменений.
/// Хранится только в памяти: после выхода из приложения история пропадает.
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    struct Entry {
        let id = UUID()
        /// Все типы каждого объекта буфера, чтобы вернуть копию в точности.
        let items: [[NSPasteboard.PasteboardType: Data]]
        /// Одна строка для меню.
        let title: String
        let symbol: String
        /// Начало текста в несколько строк — для кармана, чтобы было видно, что это.
        let preview: String
        /// «1 240 символов», «3 файла», «1920×1080».
        let detail: String
        /// Откуда скопировали.
        let app: String?
        let thumbnail: NSImage?
        let date = Date()

        /// Для перетаскивания записи из кармана: файл, текст или картинка.
        func itemProvider() -> NSItemProvider {
            guard let first = items.first else { return NSItemProvider() }
            if let data = first[.fileURL], let url = URL(dataRepresentation: data, relativeTo: nil) {
                return NSItemProvider(contentsOf: url) ?? NSItemProvider(object: url as NSURL)
            }
            if let data = first[.string], let text = String(data: data, encoding: .utf8) {
                return NSItemProvider(object: text as NSString)
            }
            let provider = NSItemProvider()
            for type in [NSPasteboard.PasteboardType.png, .tiff] {
                guard let data = first[type] else { continue }
                provider.registerDataRepresentation(forTypeIdentifier: type.rawValue, visibility: .all) { done in
                    done(data, nil)
                    return nil
                }
            }
            return provider
        }
    }

    static let limit = 10
    /// Больше не запоминаем, чтобы не держать в памяти огромные картинки.
    private static let maxBytes = 25 * 1024 * 1024

    @Published private(set) var entries: [Entry] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func clear() { entries.removeAll() }

    /// Кладёт запись обратно в буфер и поднимает её наверх истории.
    func restore(_ entry: Entry) {
        write(entry, to: .general)
        lastChange = NSPasteboard.general.changeCount
        entries.removeAll { $0.id == entry.id }
        entries.insert(entry, at: 0)
    }

    /// Отдельный буфер с содержимым записи — для кармана, общий буфер не трогаем.
    func pasteboard(for entry: Entry) -> NSPasteboard {
        let pb = NSPasteboard(name: NSPasteboard.Name("ru.chernov.karman.history"))
        write(entry, to: pb)
        return pb
    }

    private func write(_ entry: Entry, to pb: NSPasteboard) {
        pb.clearContents()
        pb.writeObjects(entry.items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        })
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Settings.clipboardHistory, let entry = Self.snapshot(pb) else { return }
        // Скопировали то же самое ещё раз — просто поднимаем наверх.
        entries.removeAll { $0.title == entry.title && $0.items == entry.items }
        entries.insert(entry, at: 0)
        if entries.count > Self.limit { entries.removeLast(entries.count - Self.limit) }
    }

    /// Пароли и служебные данные (по соглашению nspasteboard.org) не запоминаем.
    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    private static func snapshot(_ pb: NSPasteboard) -> Entry? {
        guard let pbItems = pb.pasteboardItems, !pbItems.isEmpty else { return nil }
        if pbItems.contains(where: { $0.types.contains { skipped.contains($0.rawValue) } }) { return nil }
        var bytes = 0
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        for pbItem in pbItems {
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in pbItem.types {
                guard let data = pbItem.data(forType: type) else { continue }
                bytes += data.count
                guard bytes <= maxBytes else { return nil }
                types[type] = data
            }
            if !types.isEmpty { items.append(types) }
        }
        guard !items.isEmpty, let d = describe(pb) else { return nil }
        return Entry(items: items, title: d.title, symbol: d.symbol, preview: d.preview, detail: d.detail,
                     app: NSWorkspace.shared.frontmostApplication?.localizedName, thumbnail: d.thumbnail)
    }

    private struct Description {
        var title: String
        var symbol: String
        var preview: String
        var detail: String
        var thumbnail: NSImage?
    }

    /// Подпись в меню и превью для кармана: текст, имя файла или картинка.
    private static func describe(_ pb: NSPasteboard) -> Description? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let first = urls.first {
            let title = urls.count == 1 ? first.lastPathComponent
                : "\(first.lastPathComponent) и ещё \(urls.count - 1)"
            let names = urls.prefix(3).map(\.lastPathComponent).joined(separator: "\n")
            return Description(title: title, symbol: "doc", preview: names,
                               detail: pluralRu(urls.count, "файл", "файла", "файлов"),
                               thumbnail: NSWorkspace.shared.icon(forFile: first.path))
        }
        if pb.canReadItem(withDataConformingToTypes: NSImage.imageTypes), let image = NSImage(pasteboard: pb) {
            let rep = image.representations.first
            let size = rep.map { "\($0.pixelsWide)×\($0.pixelsHigh)" } ?? ""
            return Description(title: "Картинка \(size)", symbol: "photo", preview: "Картинка",
                               detail: size, thumbnail: thumbnail(image))
        }
        if let text = pb.string(forType: .string) {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            // Пустые строки и лишние пробелы в превью только мешают.
            let lines = trimmed.split(whereSeparator: \.isNewline)
                .map { $0.split(whereSeparator: \.isWhitespace).joined(separator: " ") }
                .filter { !$0.isEmpty }
            let first = lines.first ?? trimmed
            let title = first.count > 50 ? String(first.prefix(50)) + "…" : first
            let preview = String(lines.prefix(4).joined(separator: "\n").prefix(240))
            let isLink = !trimmed.contains(where: \.isWhitespace) && trimmed.hasPrefix("http")
            return Description(title: title, symbol: isLink ? "link" : "text.alignleft", preview: preview,
                               detail: isLink ? "Ссылка" : pluralRu(trimmed.count, "символ", "символа", "символов"))
        }
        return nil
    }

    /// Маленькая копия картинки, чтобы не держать в интерфейсе оригинал.
    private static func thumbnail(_ image: NSImage) -> NSImage {
        let side: CGFloat = 96
        let s = image.size
        guard s.width > 0, s.height > 0 else { return image }
        let k = min(side / s.width, side / s.height, 1)
        let size = NSSize(width: s.width * k, height: s.height * k)
        let thumb = NSImage(size: size)
        thumb.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: size))
        thumb.unlockFocus()
        return thumb
    }
}
